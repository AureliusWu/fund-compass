(function registerFundCompassWorker() {
  'use strict'

  if (!('serviceWorker' in navigator)) return

  var script = document.currentScript
  if (!script || !script.src) return

  var baseUrl = new URL('./', script.src)
  var workerUrl = new URL('sw.js', baseUrl)
  var controlledAtLoad = Boolean(navigator.serviceWorker.controller)
  var reloadKey = 'fund-compass:sw-controller-reload-at'
  var reloadWindowMs = 10 * 1000

  navigator.serviceWorker.addEventListener('controllerchange', function () {
    // The first install does not need a reload. During an upgrade, reload once
    // so the old in-memory bundle cannot keep speaking an obsolete API shape.
    if (!controlledAtLoad) return
    var lastReload = 0
    try {
      lastReload = Number(sessionStorage.getItem(reloadKey) || 0)
    } catch (_) {
      // Storage can be disabled; the in-memory guard below still prevents a loop.
    }
    if (Date.now() - lastReload < reloadWindowMs) return
    controlledAtLoad = false
    try {
      sessionStorage.setItem(reloadKey, String(Date.now()))
    } catch (_) {
      // Reloading remains safe when sessionStorage is unavailable.
    }
    window.location.reload()
  })

  navigator.serviceWorker.register(workerUrl.href, {
    scope: baseUrl.pathname,
    updateViaCache: 'none',
  }).then(function (registration) {
    // Supports both the current self-skipping worker and any transitional
    // waiting worker generated by an earlier plugin configuration.
    if (registration.waiting) {
      registration.waiting.postMessage({ type: 'SKIP_WAITING' })
    }
    registration.addEventListener('updatefound', function () {
      var installing = registration.installing
      if (!installing) return
      installing.addEventListener('statechange', function () {
        if (installing.state === 'installed' && registration.waiting) {
          registration.waiting.postMessage({ type: 'SKIP_WAITING' })
        }
      })
    })
    // Do not rely on the browser's periodic update cadence or cached sw.js.
    return registration.update()
  }).catch(function (error) {
    console.warn('Service Worker registration failed', error)
  })
})()
